/**
 * Build a fully self-contained single-file version of the app.
 *
 *   node scripts/build-standalone.js
 *
 * Inlines the CSS, every shared module and the logo (as base64 data URIs) into
 * one .html file that runs by simply opening it — no server, no install.
 * It still talks to Open-Meteo directly and can use the offline knowledge base.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PUBLIC = path.join(ROOT, 'public');
const OUT_DIR = path.join(ROOT, 'standalone');
const OUT_FILE = path.join(OUT_DIR, 'mausam-ai.html');

const read = (p) => fs.readFileSync(path.join(PUBLIC, p), 'utf8');
const dataUri = (p) =>
  'data:image/png;base64,' + fs.readFileSync(path.join(PUBLIC, p)).toString('base64');

let html = read('index.html');

// ---- 1. inline the stylesheet -------------------------------------------------
// asset URLs carry a ?v=N cache-buster, so match them loosely
html = html.replace(
  /<link rel="stylesheet" href="css\/style\.css(\?[^"]*)?">/,
  '<style>\n' + read('css/style.css') + '\n</style>'
);

// ---- 2. inline the scripts (order matters) ------------------------------------
const scripts = ['js/data.js', 'js/engine.js', 'js/geo.js', 'js/context.js', 'js/app.js'];
const bundle = scripts
  .map((s) => '/* ===== ' + s + ' ===== */\n' + read(s))
  .join('\n\n');
// strip the individual <script src> tags (they may carry a ?v=N query)
html = html.replace(/[ \t]*<script src="js\/[a-z]+\.js(\?[^"]*)?"><\/script>\s*\n?/g, '');
// and drop the inlined bundle in just before </body>
html = html.replace('</body>', '<script>\n' + bundle + '\n</script>\n</body>');

// ---- 3. inline the images -----------------------------------------------------
const mark = dataUri('assets/logo-mark-96.png');
const favicon = dataUri('assets/favicon.png');

html = html.replace(/<link rel="manifest"[^>]*>\s*/g, '');
html = html
  .replace(/<link rel="icon"[^>]*>/g, '<link rel="icon" href="' + favicon + '">')
  .replace(/<link rel="apple-touch-icon"[^>]*>/g, '')
  .replace(/src="assets\/logo-mark\.png(\?[^"]*)?"/g, 'src="' + mark + '"');

// ---- 4. make sure it is obvious this is the offline-capable build -------------
html = html.replace(
  '</head>',
  '<!-- MAUSAM - standalone build. Generated by scripts/build-standalone.js -->\n</head>'
);

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT_FILE, html, 'utf8');

const kb = (fs.statSync(OUT_FILE).size / 1024).toFixed(1);
console.log('standalone build written:');
console.log('  ' + path.relative(process.cwd(), OUT_FILE) + '  (' + kb + ' KB)');
console.log('  open it directly in a browser — no server required.');
